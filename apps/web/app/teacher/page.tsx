"use client";

import Link from "next/link";
import {
  AlertTriangle,
  ArrowRight,
  CalendarClock,
  CheckCircle2,
  ClipboardCheck,
  ListChecks,
  PlayCircle,
  UsersRound,
} from "lucide-react";
import { useAuth } from "@/components/auth-provider";
import {
  Alert,
  Badge,
  Card,
  CardHeader,
  EmptyState,
  PageHeader,
  Skeleton,
  StatCard,
  statusTone,
  Table,
  TableWrap,
  Td,
  Th,
  Button,
} from "@/components/ui";
import { useApiData } from "@/hooks/use-api-data";
import { formatDateTime, titleCase } from "@/lib/api";
import type { TeacherDashboard } from "@/lib/types";

export default function TeacherOverviewPage() {
  const { user } = useAuth();
  const dashboard = useApiData<TeacherDashboard>("/teacher/dashboard");

  return (
    <div>
      <PageHeader
        eyebrow="Teacher"
        title={`Good to see you, ${user?.full_name?.split(" ")[0] ?? "teacher"}`}
        description="Your assigned classes, live attendance and verification reviews. Every figure is queried from the database."
        actions={
          <>
            <Link href="/teacher/sessions/new">
              <Button>
                <PlayCircle size={15} /> Start attendance
              </Button>
            </Link>
            <Link href="/teacher/reviews">
              <Button variant="secondary">
                <ListChecks size={15} /> Review queue
              </Button>
            </Link>
          </>
        }
      />

      {dashboard.error ? (
        <div className="mb-5">
          <Alert tone="danger" title="Could not load your dashboard">
            {dashboard.error}
          </Alert>
        </div>
      ) : null}

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {dashboard.loading || !dashboard.data ? (
          Array.from({ length: 4 }).map((_, index) => <Skeleton key={index} className="h-28" />)
        ) : (
          <>
            <StatCard
              label="Assigned classes"
              value={dashboard.data.classes_count}
              hint={`${dashboard.data.subjects_count} subject assignments`}
              icon={<ClipboardCheck size={18} />}
            />
            <StatCard
              label="Students in scope"
              value={dashboard.data.students_count}
              hint="Across your assigned classes"
              icon={<UsersRound size={18} />}
              tone="purple"
            />
            <StatCard
              label="Present today"
              value={dashboard.data.present_today}
              hint={`${dashboard.data.today_sessions} session(s) today`}
              icon={<CheckCircle2 size={18} />}
              tone="green"
            />
            <StatCard
              label="Review required"
              value={dashboard.data.review_pending}
              hint={
                dashboard.data.failed_attempts_today
                  ? `${dashboard.data.failed_attempts_today} rejected attempt(s) today`
                  : "No rejected attempts today"
              }
              icon={<AlertTriangle size={18} />}
              tone={dashboard.data.review_pending ? "amber" : "blue"}
            />
          </>
        )}
      </div>

      <div className="mt-6 grid gap-5 xl:grid-cols-[1.25fr_1fr]">
        <Card>
          <CardHeader
            title="Recent attendance sessions"
            description="Latest sessions you created, with verified counts."
            action={
              <Link href="/teacher/sessions" className="text-xs font-semibold text-brand hover:underline">
                All sessions
              </Link>
            }
          />
          {dashboard.loading ? (
            <div className="p-4">
              <Skeleton className="h-44" />
            </div>
          ) : !dashboard.data?.recent_sessions.length ? (
            <EmptyState
              icon={<CalendarClock size={20} />}
              title="No attendance sessions yet"
              description="Start a session for one of your assigned classes. A dynamic QR and PIN will be generated by the backend."
              action={
                <Link href="/teacher/sessions/new">
                  <Button size="sm">Start your first session</Button>
                </Link>
              }
            />
          ) : (
            <TableWrap>
              <Table>
                <thead>
                  <tr>
                    <Th>Session</Th>
                    <Th>Status</Th>
                    <Th>Attendance</Th>
                    <Th />
                  </tr>
                </thead>
                <tbody>
                  {dashboard.data.recent_sessions.map((session) => (
                    <tr key={session.id}>
                      <Td>
                        <p className="font-medium text-ink">{session.subject_name}</p>
                        <p className="text-[11px] text-muted">
                          {session.class_name} · {formatDateTime(session.starts_at)}
                        </p>
                      </Td>
                      <Td>
                        <Badge tone={statusTone(session.status)}>{titleCase(session.status)}</Badge>
                      </Td>
                      <Td>
                        <span className="font-semibold text-ink">{session.accepted}</span>
                        <span className="text-muted"> / {session.eligible_students}</span>
                        {session.review_required ? (
                          <span className="ml-2 text-[11px] font-medium text-[#B54708]">
                            {session.review_required} review
                          </span>
                        ) : null}
                      </Td>
                      <Td className="text-right">
                        <Link
                          href={`/teacher/sessions/${session.id}`}
                          className="inline-flex items-center gap-1 text-xs font-semibold text-brand hover:underline"
                        >
                          Open <ArrowRight size={12} />
                        </Link>
                      </Td>
                    </tr>
                  ))}
                </tbody>
              </Table>
            </TableWrap>
          )}
        </Card>

        <Card>
          <CardHeader
            title="Verification review queue"
            description="Attempts that need a teacher decision."
            action={
              <Link href="/teacher/reviews" className="text-xs font-semibold text-brand hover:underline">
                Open queue
              </Link>
            }
          />
          {dashboard.loading ? (
            <div className="p-4">
              <Skeleton className="h-44" />
            </div>
          ) : !dashboard.data?.review_queue.length ? (
            <EmptyState
              icon={<CheckCircle2 size={20} />}
              title="No open reviews"
              description="Attempts with missing or borderline evidence appear here instead of being silently rejected."
            />
          ) : (
            <ul className="divide-y divide-line">
              {dashboard.data.review_queue.map((review) => (
                <li key={review.id} className="px-5 py-3">
                  <div className="flex items-start justify-between gap-2">
                    <div>
                      <p className="text-sm font-semibold text-ink">{review.student_name}</p>
                      <p className="text-[11px] text-muted">
                        {review.roll_number} · {review.subject_name}
                      </p>
                    </div>
                    <Badge tone="amber">Review</Badge>
                  </div>
                  <p className="mt-1.5 line-clamp-2 text-xs text-muted">{review.reason}</p>
                </li>
              ))}
            </ul>
          )}
        </Card>
      </div>

      <div className="mt-6 grid gap-4 sm:grid-cols-3">
        {[
          ["Start a session", "Pick an assigned class and open a live window.", "/teacher/sessions/new", PlayCircle],
          ["My students", "See enrolled students across your assigned classes.", "/teacher/students", UsersRound],
          ["Attendance reports", "Review subject and student attendance percentages.", "/teacher/reports", ScrollTextIcon],
        ].map(([label, detail, href, Icon]) => {
          const Component = Icon as typeof PlayCircle;
          return (
            <Link
              key={label as string}
              href={href as string}
              className="rounded-xl border border-line bg-white p-4 transition-colors hover:border-brand/40 hover:bg-active"
            >
              <Component size={17} className="text-brand" />
              <p className="mt-2 text-sm font-semibold text-ink">{label as string}</p>
              <p className="mt-1 text-xs text-muted">{detail as string}</p>
            </Link>
          );
        })}
      </div>
    </div>
  );
}

function ScrollTextIcon(props: { size?: number; className?: string }) {
  return <ClipboardCheck {...props} />;
}
